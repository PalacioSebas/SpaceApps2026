// Reglas del perfil demo y precedencia de preferencias, sin navegador ni npm.
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const context = vm.createContext({});
vm.runInContext(fs.readFileSync(path.join(__dirname, "../static/demo-profiles.js"), "utf8"), context);
const { Store, STORAGE_KEY, effectiveSettings } = context.DemoProfiles;
const values = new Map();
const storage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) };
const store = new Store(storage);
assert.equal(store.get(), null);
store.enter("principiante", { alias: "Ana" });
assert.equal(effectiveSettings(store.get()).fps, 1);
store.remember({ maxFrames: 102, fov: 1, fps: 6 });
assert.equal(effectiveSettings(store.get()).maxFrames, 102, "El perfil principiante permite los mismos parámetros avanzados");
assert.equal(effectiveSettings(store.get()).fov, 1);
store.remember({ fps: 6, maxFrames: 7, fov: .12, showFlags: false });
store.update({ level: "avanzado", explanations: "simple" });
assert.equal(store.get().alias, "Ana");
assert.equal(effectiveSettings(store.get()).fps, 6, "Cambiar el nivel respeta los ajustes manuales");
assert.equal(effectiveSettings(store.get()).maxFrames, 7);
assert.equal(effectiveSettings(store.get()).showFlags, false);
assert.equal(store.get().explanations, "simple");
store.rememberRegion(269.452075, 4.693364, true);
const reloaded = new Store(storage);
assert.equal(reloaded.get().alias, "Ana");
assert.equal(effectiveSettings(reloaded.get()).fov, .12);
assert.equal(reloaded.get().lastRegion.temporal, true);
reloaded.leave();
assert.equal(reloaded.get(), null);
reloaded.enter("explorador");
assert.equal(effectiveSettings(reloaded.get()).maxFrames, 10, "Las cuentas mantienen preferencias separadas");
assert.notEqual(reloaded.get().alias, "Ana");
reloaded.enter("principiante");
assert.equal(effectiveSettings(reloaded.get()).maxFrames, 7);
reloaded.reset();
assert.equal(effectiveSettings(reloaded.get()).maxFrames, 16);
assert.equal(effectiveSettings(reloaded.get()).showFlags, true);
assert.equal(reloaded.get().alias, "Ana", "Restaurar parámetros conserva el perfil");
reloaded.remember({ maxFrames: 100000, fov: -1, fps: 3, showFlags: "false", viewMode: "unknown" });
assert.equal(effectiveSettings(reloaded.get()).maxFrames, 16, "Se rechazan valores fuera de los límites");
reloaded.leave(true);
assert.equal(new Store(storage).data.entered, true);
assert.equal(new Store(storage).get(), null);
values.set(STORAGE_KEY, "{malformed");
const damaged = new Store(storage);
assert.equal(damaged.get(), null);
damaged.enter("principiante");
assert.equal(damaged.persistent, true, "Se puede recuperar un registro corrupto");
const blocked = new Store({ getItem() { throw new Error("blocked"); }, setItem() { throw new Error("quota"); } });
blocked.enter("avanzado");
blocked.remember({ fps: 6 });
assert.equal(blocked.persistent, false);
assert.equal(effectiveSettings(blocked.get()).fps, 6, "Sin almacenamiento la sesión sigue funcionando");
assert.throws(() => blocked.enter("admin"));
console.log("Perfiles: persistencia, aislamiento, precedencia, restauración y almacenamiento no disponible correctos.");
